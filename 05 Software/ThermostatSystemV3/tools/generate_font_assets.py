"""Embed the four used VLW fonts unchanged. Run with --check to verify output."""
from pathlib import Path
import argparse
import struct

root = Path(__file__).resolve().parents[1]
names = ('Noway_Light18', 'Noway_Light24', 'Noway_Medium24', 'Noway_Medium32', 'Noway_Medium60')
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
lines = ['#pragma once', '// Generated by test/generate_font_assets.py. Original VLW bytes, unchanged.']
total = 0
for name in names:
    data = (root / 'shared/assets/fonts' / (name + '.vlw')).read_bytes()
    count = struct.unpack_from('>I', data)[0]
    assert 0 < count < 65536 and len(data) >= 24 + count*28
    bitmap_end = 24 + count*28
    for i in range(count):
        code, height, width, advance, dy, dx, padding = struct.unpack_from('>7i', data, 24+i*28)
        assert 0 <= code <= 65535 and 0 <= width <= 255 and 0 <= height <= 255
        bitmap_end += height*width
    assert bitmap_end <= len(data), name
    lines.append(f'static const uint8_t font_{name}[] PROGMEM = {{')
    lines.extend(','.join(f'0x{b:02x}' for b in data[i:i+24])+',' for i in range(0,len(data),24))
    lines.append('};')
    total += len(data)
    print(f'{name}: {len(data)} flash bytes; {count*12} glyph-metric heap bytes while loaded (plus allocation overhead)')
output = '\n'.join(lines)+'\n'
target = root / 'shared/assets/include/font_assets.h'
if args.check:
    assert target.read_text() == output, 'Generated fonts differ from source VLW data'
else:
    target.write_text(output)
print(f'{"Verified" if args.check else "Generated"} five fonts: {total} bytes; glyph tables and bitmap bounds valid')
