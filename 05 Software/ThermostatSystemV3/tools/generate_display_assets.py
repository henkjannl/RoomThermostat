"""Convert original JPEG artwork to RGB565 flash assets. Requires Pillow."""
from pathlib import Path
from display_asset_sources import selected_assets,opaque_image

root = Path(__file__).resolve().parents[1]
files = selected_assets(root)
out = ['#pragma once', '// Generated by test/generate_display_assets.py; do not edit.',
       'struct FlashImage { const char *name; uint16_t width, height; const uint16_t *pixels; };']
entries = []
pixel_bytes=0
for n, (runtime_name,path) in enumerate(files):
    im = opaque_image(path)
    assert im.width<=320 and im.height<=240,(path,im.size)
    if path.suffix.lower()=='.png':assert im.size==(32,32),(path,im.size)
    pixel_bytes+=im.width*im.height*2
    pixels = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r,g,b in im.getdata()]
    out.append(f'static const uint16_t image{n}[] PROGMEM = {{')
    out.extend(','.join(f'0x{v:04x}' for v in pixels[i:i+16])+',' for i in range(0,len(pixels),16))
    out.append('};')
    entries.append(f'{{"/{runtime_name}",{im.width},{im.height},image{n}}}')
out.append('static const FlashImage flashImages[] = {' + ',\n'.join(entries) + '};')
(root / 'shared/assets/include/display_assets.h').write_text('\n'.join(out)+'\n')
print(f'{len(files)} images; {pixel_bytes} pixel bytes in flash; PNG overrides and white alpha composition applied')
