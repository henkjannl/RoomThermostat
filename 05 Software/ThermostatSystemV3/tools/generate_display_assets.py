"""Convert original JPEG artwork to RGB565 flash assets. Requires Pillow."""
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
files = (sorted((root / 'shared/assets/icons').glob('icon*.jpg')) +
         sorted((root / 'shared/assets/icons').glob('remote-*.png')) +
         sorted((root / 'shared/assets/icons').glob('battery-*.png')) + [root / 'shared/assets/icons/HomeScreen.jpg'])
out = ['#pragma once', '// Generated by test/generate_display_assets.py; do not edit.',
       'struct FlashImage { const char *name; uint16_t width, height; const uint16_t *pixels; };']
entries = []
for n, path in enumerate(files):
    im = Image.open(path).convert('RGB')
    pixels = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r,g,b in im.getdata()]
    out.append(f'static const uint16_t image{n}[] PROGMEM = {{')
    out.extend(','.join(f'0x{v:04x}' for v in pixels[i:i+16])+',' for i in range(0,len(pixels),16))
    out.append('};')
    entries.append(f'{{"/{path.name}",{im.width},{im.height},image{n}}}')
out.append('static const FlashImage flashImages[] = {' + ',\n'.join(entries) + '};')
(root / 'shared/assets/include/display_assets.h').write_text('\n'.join(out)+'\n')
print(f'{len(files)} images; {sum(Image.open(p).width*Image.open(p).height*2 for p in files)} pixel bytes in flash')
